// Optional release signing: create keystore.properties in the project root
// (see docs/BUILDING.md). Without it the release APK is signed with the debug key.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.offlinetranscriber"
    compileSdk = 35
    ndkVersion = "27.2.12479018"

    defaultConfig {
        applicationId = "com.offlinetranscriber"
